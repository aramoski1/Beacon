/**
 * Generates lib/database.types.ts from the live Postgres schema.
 *
 * Usage: npm run types:gen
 * Requires: DATABASE_URL in .env.local
 *
 * Output is committed so CI does not need a database. Re-run after migrations.
 */
import { writeFileSync } from "fs";
import { join } from "path";
import { fileURLToPath } from "url";
import { Client } from "pg";

const DATABASE_URL = process.env.DATABASE_URL;
if (!DATABASE_URL) {
  console.error("DATABASE_URL is not set in .env.local");
  process.exit(1);
}

const __dirname = fileURLToPath(new URL(".", import.meta.url));

function pgToTs(udt: string, isNullable: boolean): string {
  const base = (() => {
    if (udt.endsWith("[]")) return "Json";
    switch (udt) {
      case "uuid":
      case "text":
      case "varchar":
      case "bpchar":
      case "citext":
      case "name":
      case "date":
      case "time":
      case "timetz":
      case "timestamp":
      case "timestamptz":
      case "interval":
        return "string";
      case "bool":
        return "boolean";
      case "int2":
      case "int4":
      case "int8":
      case "float4":
      case "float8":
      case "numeric":
      case "money":
        return "number";
      case "json":
      case "jsonb":
        return "Json";
      default:
        return "string";
    }
  })();
  return isNullable ? `${base} | null` : base;
}

type ColRow = {
  table_name: string;
  column_name: string;
  udt_name: string;
  is_nullable: "YES" | "NO";
};

async function main() {
  const client = new Client({
    connectionString: DATABASE_URL,
    ssl: { rejectUnauthorized: false },
  });
  await client.connect();

  const { rows } = await client.query<ColRow>(`
    SELECT table_name, column_name, udt_name, is_nullable
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name NOT LIKE 'pg_%'
    ORDER BY table_name, ordinal_position
  `);
  await client.end();

  const tables = new Map<string, ColRow[]>();
  for (const row of rows) {
    const list = tables.get(row.table_name) ?? [];
    list.push(row);
    tables.set(row.table_name, list);
  }

  const tableBlocks: string[] = [];
  for (const [table, cols] of tables) {
    const rowFields = cols
      .map((c) => `      ${c.column_name}: ${pgToTs(c.udt_name, c.is_nullable === "YES")}`)
      .join("\n");
    const insertFields = cols
      .map((c) => {
        const optional = c.is_nullable === "YES" || c.column_name === "id" || c.column_name.endsWith("_at");
        return `      ${c.column_name}${optional ? "?" : ""}: ${pgToTs(c.udt_name, true)}`;
      })
      .join("\n");
    const updateFields = cols
      .map((c) => `      ${c.column_name}?: ${pgToTs(c.udt_name, true)}`)
      .join("\n");

    tableBlocks.push(`    ${table}: {
      Row: {
${rowFields}
      }
      Insert: {
${insertFields}
      }
      Update: {
${updateFields}
      }
      Relationships: []
    }`);
  }

  const out = `// Generated by scripts/generate-database-types.ts — do not edit by hand.
// Re-run: npm run types:gen
//
// Not yet passed to createServerClient<Database>: Insert types treat NOT NULL
// columns as required even when they have database defaults, which would break
// existing .insert()/.update() calls. Use Tables<"properties"> etc. at call sites
// until those defaults are marked optional in this generator.

export type Json =
  | string
  | number
  | boolean
  | null
  | { [key: string]: Json | undefined }
  | Json[];

export type Database = {
  public: {
    Tables: {
${tableBlocks.join("\n")}
    }
    Views: {
      [_ in never]: never
    }
    Functions: {
      [_ in string]: {
        Args: Record<string, unknown>
        Returns: unknown
      }
    }
    Enums: {
      [_ in never]: never
    }
    CompositeTypes: {
      [_ in never]: never
    }
  }
}

export type Tables<T extends keyof Database["public"]["Tables"]> =
  Database["public"]["Tables"][T]["Row"];
`;

  const dest = join(__dirname, "..", "lib", "database.types.ts");
  writeFileSync(dest, out, "utf8");
  console.log(`Wrote ${dest} (${tables.size} tables)`);
}

main().catch((e) => {
  console.error(e.message);
  process.exit(1);
});
